#!/usr/bin/env node
// Task board: validates tasks/T*.md front matter and writes tasks/BOARD.md and tasks/board.json.
// Usage: node scripts/tasks.mjs [--check]   (--check validates without writing)

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const STATUSES = ["backlog", "ready", "in-progress", "review", "done", "blocked"];
export const MODELS = ["sonnet-5.5", "opus-5.5"];
export const SIZES = { S: 1, M: 2, L: 3 };
const STARTED = new Set(["in-progress", "review", "done"]);

export function parseTask(text, file) {
	const match = /^---\n([\s\S]*?)\n---/.exec(text);
	if (!match) throw new Error(`${file}: missing front matter`);
	const task = { file };
	for (const line of match[1].split("\n")) {
		const kv = /^([a-z_]+):\s*(.*)$/.exec(line.trim());
		if (!kv) continue;
		const [, key, raw] = kv;
		let value = raw;
		if (raw.startsWith("[") && raw.endsWith("]")) {
			const inner = raw.slice(1, -1).trim();
			value = inner ? inner.split(",").map((s) => s.trim()) : [];
		} else if (raw.startsWith('"') && raw.endsWith('"')) {
			value = raw.slice(1, -1);
		} else if (/^\d+$/.test(raw)) {
			value = Number(raw);
		}
		task[key] = value;
	}
	task.depends_on ??= [];
	task.spec ??= [];
	return task;
}

export function validate(tasks) {
	const errors = [];
	const byId = new Map();
	for (const t of tasks) {
		if (byId.has(t.id)) errors.push(`duplicate id ${t.id}`);
		byId.set(t.id, t);
		if (!MODELS.includes(t.model)) errors.push(`${t.id}: unknown model "${t.model}"`);
		if (!STATUSES.includes(t.status)) errors.push(`${t.id}: unknown status "${t.status}"`);
		if (!(t.size in SIZES)) errors.push(`${t.id}: unknown size "${t.size}"`);
	}
	for (const t of tasks) {
		for (const d of t.depends_on) {
			const dep = byId.get(d);
			if (!dep) {
				errors.push(`${t.id} depends on unknown ${d}`);
				continue;
			}
			if (STARTED.has(t.status) && dep.status !== "done") {
				errors.push(`${t.id} is ${t.status} but ${d} is ${dep.status}`);
			}
		}
	}
	// Cycle detection (iterative DFS with colours).
	const colour = new Map();
	for (const start of byId.keys()) {
		if (colour.get(start)) continue;
		const stack = [[start, 0]];
		colour.set(start, 1);
		while (stack.length) {
			const frame = stack.at(-1);
			const deps = byId.get(frame[0])?.depends_on ?? [];
			if (frame[1] >= deps.length) {
				colour.set(frame[0], 2);
				stack.pop();
				continue;
			}
			const next = deps[frame[1]++];
			if (!byId.has(next)) continue;
			if (colour.get(next) === 1) {
				errors.push(`cycle through ${frame[0]} → ${next}`);
				return errors;
			}
			if (!colour.get(next)) {
				colour.set(next, 1);
				stack.push([next, 0]);
			}
		}
	}
	return errors;
}

export function buildBoard(tasks) {
	const byId = Object.fromEntries(tasks.map((t) => [t.id, { ...t, unblocks: [] }]));
	for (const t of tasks) for (const d of t.depends_on) byId[d]?.unblocks.push(t.id);
	for (const t of Object.values(byId)) t.unblocks.sort();

	const columns = Object.fromEntries(STATUSES.map((s) => [s, []]));
	for (const t of Object.values(byId)) {
		let column = t.status;
		if (column === "backlog" && t.depends_on.every((d) => byId[d]?.status === "done")) column = "ready";
		t.column = column;
		columns[column].push(t.id);
	}
	for (const c of Object.values(columns)) c.sort();

	// Critical path: longest chain of remaining work, weighted by size.
	const memo = new Map();
	const longest = (id) => {
		if (memo.has(id)) return memo.get(id);
		const t = byId[id];
		const own = t.status === "done" ? 0 : SIZES[t.size];
		let best = { weight: own, path: [id] };
		for (const d of t.depends_on) {
			const sub = longest(d);
			if (sub.weight + own > best.weight || (sub.weight + own === best.weight && sub.path.length + 1 > best.path.length)) {
				best = { weight: sub.weight + own, path: [...sub.path, id] };
			}
		}
		memo.set(id, best);
		return best;
	};
	let critical = { weight: 0, path: [] };
	for (const id of Object.keys(byId)) {
		const c = longest(id);
		if (c.weight > critical.weight) critical = c;
	}
	const criticalPath = critical.path.filter((id) => byId[id].status !== "done");
	return { tasks: byId, columns, criticalPath, criticalWeight: critical.weight };
}

function renderBoard(board) {
	const label = { backlog: "Backlog", ready: "Ready", "in-progress": "In progress", review: "Review", done: "Done", blocked: "Blocked" };
	const order = ["ready", "in-progress", "review", "blocked", "backlog", "done"];
	const lines = [
		"# Task board",
		"",
		"Generated by `node scripts/tasks.mjs` from the task files. Do not edit by hand.",
		"",
		"| Column | Tasks |",
		"| --- | --- |",
		...order.map((c) => `| ${label[c]} | ${board.columns[c].length} |`),
		"",
		`**Critical path** (${board.criticalWeight} size units): ${board.criticalPath.join(" → ")}`,
		"",
	];
	for (const c of order) {
		lines.push(`## ${label[c]}`, "");
		if (!board.columns[c].length) lines.push("_None_", "");
		for (const id of board.columns[c]) {
			const t = board.tasks[id];
			const deps = t.depends_on.length ? ` · needs ${t.depends_on.join(", ")}` : "";
			lines.push(`- [${id}](${t.file}) ${t.title} · ${t.model} · ${t.size} · ${t.edition}${deps}`);
		}
		lines.push("");
	}
	return lines.join("\n");
}

function main() {
	const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "tasks");
	const files = readdirSync(dir).filter((f) => /^T\d+.*\.md$/.test(f)).sort();
	const tasks = files.map((f) => parseTask(readFileSync(join(dir, f), "utf8"), f));
	const errors = validate(tasks);
	if (errors.length) {
		console.error(errors.map((e) => `✖ ${e}`).join("\n"));
		process.exit(1);
	}
	const board = buildBoard(tasks);
	if (!process.argv.includes("--check")) {
		writeFileSync(join(dir, "BOARD.md"), renderBoard(board));
		writeFileSync(join(dir, "board.json"), `${JSON.stringify(board, null, "\t")}\n`);
	}
	console.log(`✔ ${tasks.length} tasks valid · ready: ${board.columns.ready.join(", ") || "none"}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
