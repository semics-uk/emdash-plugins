// T103: the registry listings (profile sections, icon, banner, screenshots) of both Free cores.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { repoRoot } from "../build.mjs";
import { pngSize, readManifest } from "./helpers.mjs";

const CORES = ["events", "esign"];
const SECTIONS = ["description", "installation", "faq", "security"];
/** The registry's caps (plugin-cli 0.13.3: sections, artifacts and `collectAssets`). */
const SECTION_BYTES = 20_000;
const SECTION_GRAPHEMES = 2_000;
const ARTIFACT_BYTES = 1024 * 1024;
const SCREENSHOT = { width: 1920, height: 1080 };
const SCREENSHOT_SPEC = "apps/playground/e2e/t103-screenshots.spec.ts";

const graphemes = (s) => [...new Intl.Segmenter("en", { granularity: "grapheme" }).segment(s)].length;

for (const pkg of CORES) {
	const dir = join(repoRoot, "packages", pkg);

	test(`${pkg}: the listing has a name, keywords and the four profile sections, each within the registry caps`, () => {
		const manifest = readManifest(pkg);
		assert.ok(manifest.name, "name");
		assert.ok(manifest.keywords?.length > 0 && manifest.keywords.length <= 5, "1-5 keywords");
		for (const key of SECTIONS) {
			const ref = manifest.sections?.[key];
			assert.ok(ref?.file, `sections.${key} is a { file } ref`);
			const text = readFileSync(join(dir, ref.file), "utf8");
			assert.ok(Buffer.byteLength(text) <= SECTION_BYTES, `${key}: at most ${SECTION_BYTES} bytes`);
			assert.ok(
				graphemes(text) <= SECTION_GRAPHEMES,
				`${key}: ${graphemes(text)} graphemes, at most ${SECTION_GRAPHEMES}`,
			);
			assert.match(text, /https:\/\/github\.com\/semics-uk\/emdash-plugins/, `${key} links to the docs`);
		}
	});

	test(`${pkg}: icon, banner and screenshots are PNGs the registry accepts, generated by Playwright`, () => {
		const { icon, banner, screenshots } = readManifest(pkg).release?.artifacts ?? {};
		assert.ok(icon && banner && screenshots?.length >= 2 && screenshots.length <= 8, "icon, banner, 2-8 screenshots");
		const spec = readFileSync(join(repoRoot, SCREENSHOT_SPEC), "utf8");
		for (const ref of [icon, banner, ...screenshots]) {
			const file = join(dir, ref.file);
			assert.ok(existsSync(file), `${ref.file} exists`);
			assert.ok(statSync(file).size <= ARTIFACT_BYTES, `${ref.file} is at most 1 MiB`);
			const size = pngSize(readFileSync(file));
			assert.ok(size, `${ref.file} is a PNG`);
			assert.ok(size.width <= SCREENSHOT.width && size.height <= SCREENSHOT.height, `${ref.file} fits 1920x1080`);
			const name = ref.file.replace(/^listing\//, "");
			assert.ok(spec.includes(`"${pkg}", "${name}"`), `${SCREENSHOT_SPEC} generates ${name}`);
		}
		assert.deepEqual(pngSize(readFileSync(join(dir, icon.file))), { width: 256, height: 256 }, "icon is 256x256");
	});

	test(`${pkg}: emdash-plugin validate accepts the listing`, () => {
		const cli = join(dir, "node_modules", ".bin", "emdash-plugin");
		const run = spawnSync(cli, ["validate", "--json"], { cwd: dir, encoding: "utf8" });
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.equal(JSON.parse(run.stdout).ok, true);
	});
}
