/** Width of every byte 0-255 for one face; control codes are 0 (never emitted). */
function table(ascii: number[], high: number[], latin1: number[]): Uint16Array {
	const widths = new Uint16Array(256);
	widths.set(ascii, 0x20);
	widths.set(high, 0x80);
	widths.set(latin1, 0xa0);
	return widths;
}

